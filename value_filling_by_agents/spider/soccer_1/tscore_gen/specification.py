def _load_json(path):
    try:
        with open(path) as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


def load_specification(root=None):
    """Load tscore_gen/specification.json if present; fall back to built-in constants."""
    candidates = []
    if root:
        candidates.append(os.path.join(root, 'specification.json'))
    candidates.append(os.path.join(os.path.dirname(__file__), 'specification.json'))
    for p in candidates:
        spec = _load_json(p)
        if spec:
            return spec
    return {}


def boundary_values(table, column):
    """Return the comparison-boundary pool for a column, or []."""
    return list(BOUNDARY_VALUES.get((table, column), []))


def enum_values(table, column):
    """Return the enum pool for a text column, or []."""
    return list(ENUM_VALUES.get((table, column), []))


def free_text_values(table, column):
    """Return the observed free-text pool for a column, or []."""
    return list(FREE_TEXT_VALUES.get((table, column), []))


def range_formula(table, column):
    """Return (lo, hi) for a numeric column, or None."""
    return RANGE_FORMULAS.get((table, column))


def is_unique_sequential(table, column):
    """True for key-like columns generated by a sequential counter starting at 1."""
    return (table, column) in UNIQUE_SEQUENTIAL


def unique_text_prefix(table, column):
    """Return the unique-sequential text prefix for a column, or None."""
    return UNIQUE_SEQUENTIAL_TEXT.get((table, column))


def null_share(table, column, original_values):
    """NULL share for a nullable column: compact share, clamped to [0.05, 0.30]."""
    key = '%s.%s' % (table, column)
    if key not in NULL_TARGETS:
        return 0.0
    vals = original_values or []
    if not vals:
        return 0.05
    n_null = sum(1 for v in vals if v is None)
    share = n_null / float(len(vals))
    return min(0.30, max(0.05, share))


def is_tie_column(table, column):
    """True for ORDER BY columns that should carry tied values."""
    return (table, column) in TIE_COLUMNS


def table_size(table):
    """Per-instance row count for a table."""
    return TABLE_SIZES.get(table, 230)
